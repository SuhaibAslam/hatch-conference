const fs = require('fs');
const path = require('path');

const repositoryRoot = path.resolve(__dirname, '..');
const outputPath = path.join(__dirname, 'content.generated.js');
const roots = ['workshop', 'skills', 'tool-setup', 'references'];

function collectMarkdown(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) return collectMarkdown(absolutePath);
    return entry.isFile() && entry.name.endsWith('.md') ? [absolutePath] : [];
  });
}

const content = {};
for (const root of roots) {
  for (const absolutePath of collectMarkdown(path.join(repositoryRoot, root))) {
    const relativePath = path.relative(repositoryRoot, absolutePath).split(path.sep).join('/');
    content[relativePath] = fs.readFileSync(absolutePath, 'utf8');
  }
}

const generated = `// Generated by site/build-content.js from canonical repository Markdown.\nwindow.WORKSHOP_CONTENT = ${JSON.stringify(content, null, 2)};\n`;
fs.writeFileSync(outputPath, generated);
console.log(`Bundled ${Object.keys(content).length} workshop resources.`);
